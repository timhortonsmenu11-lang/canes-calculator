export function toNumber(value: NutritionValue) {
  if (value === "<1") {
    return 0.5;
  }

  if (value === "<5") {
    return 4;
  }

  return value;
}

export function formatValue(value: NutritionValue, unit = "") {
  if (value === "<1") {
    return `<1${unit}`;
  }

  if (value === "<5") {
    return `<5${unit}`;
  }

  return `${value}${unit}`;
}


export type MenuCategory =
  | "Individual Items"
  | "Combination Meals"
  | "Drinks"
  | "Condiments";

export type NutritionValue = number | "<1" | "<5";

export type NutritionItem = {
  id: string;
  name: string;
  category: MenuCategory;
  serving: string;
  calories: number;
  totalFat: NutritionValue;
  saturatedFat: NutritionValue;
  transFat: NutritionValue;
  cholesterol: NutritionValue;
  sodium: NutritionValue;
  carbs: NutritionValue;
  dietaryFiber: NutritionValue;
  sugar: NutritionValue;
  protein: NutritionValue;
  allergen: string;
};

